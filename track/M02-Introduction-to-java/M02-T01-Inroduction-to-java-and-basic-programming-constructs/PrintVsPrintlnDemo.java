class PrintVsPrintlnDemo {
    public static void main(String[] args){
        System.out.print("Hello World");
        System.out.println("Welcome to java programming");
        
        // print statement does not prints the new line it prints the content in the same line where cursor is blinking 
        // println statement prints the content and the cursor moves to the next line where the next content is to be printed

        System.out.println("---Days of the week--- ");
        System.out.println("Monday");
        System.out.print("Tuesday");
        System.out.println("Wednesday");
        System.out.println("Thursday");
        System.out.print("Friday");
        System.out.println("Saturday");
        System.out.println("Sunday");
    }
}
